import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? "playwright");
const sharp = createRequire(require.resolve("next/package.json"))("sharp");
const base = process.env.STUDIO_URL ?? "http://localhost:3102";
const output = resolve("artifacts/studio");
await mkdir(output, { recursive: true });
const manifest = JSON.parse(
  await readFile("public/models/cars/manifest.json", "utf8"),
);
// These are screenshots of the actual models, generated by qa-studio-models.
for (const suffix of ["", "-front"]) {
  const thumbs = [];
  for (const [index, model] of manifest.models.entries()) {
    const png = await sharp(
      await readFile(`${output}/${model.id}${suffix}.png`),
    )
      .resize(288, 180, { fit: "contain", background: "#e2e4da" })
      .png()
      .toBuffer();
    thumbs.push({
      input: png,
      left: (index % 5) * 288,
      top: Math.floor(index / 5) * 210,
    });
    const label = Buffer.from(
      `<svg width="288" height="30"><text x="8" y="20" font-family="sans-serif" font-size="12" fill="#0e2d30">${model.id}</text></svg>`,
    );
    thumbs.push({
      input: label,
      left: (index % 5) * 288,
      top: Math.floor(index / 5) * 210 + 180,
    });
  }
  await sharp({
    create: { width: 1440, height: 1050, channels: 3, background: "#e2e4da" },
  })
    .composite(thumbs)
    .png()
    .toFile(`${output}/contact-sheet${suffix}.png`);
}
const browser = await chromium.launch({
  channel: "msedge",
  headless: true,
  args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
});
const context = await browser.newContext({
  viewport: { width: 1440, height: 1080 },
  deviceScaleFactor: 1,
});
try {
  const page = await context.newPage();
  const errors = [];
  const badResponses = [];
  let modelRequests = 0;
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => {
    if (message.type() === "error") errors.push(message.text());
  });
  page.on("response", (response) => {
    if (response.status() >= 400)
      badResponses.push(`${response.status()} ${response.url()}`);
  });
  page.on("request", (request) => {
    if (request.url().endsWith(".glb")) modelRequests++;
  });
  await page.goto(`${base}/studio`, { waitUntil: "networkidle" });
  if (modelRequests) throw new Error("Unrequested3Ddownload");
  for (let index = 0; index < 25; index++) {
    await page
      .getByLabel("Car model collection", { exact: true })
      .getByRole("button")
      .nth(index)
      .click();
    const preview = page.getByRole("img", { name: /3D model preview/ });
    await preview.evaluate((image) => image.decode());
  }
  if (modelRequests) throw new Error("BrowsingcarsmustnotdownloadGLBs");
  await page
    .getByLabel("Car model collection", { exact: true })
    .getByRole("button")
    .filter({ hasText: "M3 · E30" })
    .click();
  await page.evaluate(() => {
    window.scrollTo(0, 0);
    document.activeElement?.blur();
  });
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: true });
  await page.getByRole("button", { name: "Load interactive 3D" }).click();
  const viewer = page.locator("section[data-model-id]");
  await viewer
    .locator("[role=status]")
    .first()
    .filter({ hasText: "Model ready" })
    .waitFor({ timeout: 60000 });
  const original = await viewer.locator("canvas").screenshot();
  await page.getByRole("button", { name: "Estoril blue" }).click();
  const painted = await viewer.locator("canvas").screenshot();
  if (original.equals(painted)) throw new Error("Paintdidnotchangethemodel");
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Save image", exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(`${output}/capcar-e30-export.png`);
  const dimensions = await sharp(`${output}/capcar-e30-export.png`).metadata();
  if (!dimensions.width || !dimensions.height)
    throw new Error("InvalidPNGexport");
  await page.setViewportSize({ width: 390, height: 844 });
  if (
    await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
  )
    throw new Error("Mobileoverflow");
  await page.getByRole("button", { name: "Side view" }).click();
  await viewer.screenshot({ path: `${output}/mobile-active.png` });
  await page.getByRole("button", { name: "Stop 3D" }).click();
  await page.evaluate(() => {
    window.scrollTo(0, 0);
    document.activeElement?.blur();
  });
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: true });
  await page
    .getByRole("combobox", { name: "Choose a car", exact: true })
    .selectOption("nissan-gt-r");
  if ((await viewer.getAttribute("data-model-id")) !== "nissan-gt-r")
    throw new Error("Mobileselectfailed");
  await page.getByRole("button", { name: "Save direction" }).click();
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Restore direction" }).click();
  if ((await viewer.getAttribute("data-model-id")) !== "nissan-gt-r")
    throw new Error("Restorefailed");
  const garage = await context.newPage();
  await garage.goto(`${base}/studio`);
  await garage.evaluate(() => {
    localStorage.setItem(
      "capcar.vehicles.v1",
      JSON.stringify([
        {
          id: "qa-e30",
          createdAt: "2026-10-18T12:00:00Z",
          make: "BMW",
          model: "M3",
          platform: "E30",
          productionYear: 1990,
          bodyStyle: "Coupe",
          engineCode: "S14",
          transmission: "Manual",
          mileage: 100000,
        },
      ]),
    );
    localStorage.setItem(
      "capcar.builds.v1",
      JSON.stringify({
        builds: [
          {
            id: "qa-build",
            vehicleId: "qa-e30",
            createdAt: "2026-10-18T12:00:00Z",
            name: "Classic QA",
            goal: "OEM+ daily",
            description: "Isolated browser test of the free model library.",
            budget: 3000,
            status: "planning",
          },
        ],
        items: [],
      }),
    );
  });
  await garage.goto(`${base}/garage/qa-e30/builds/qa-build/visualize`, {
    waitUntil: "networkidle",
  });
  let garageResult = "requires-account";
  if (!garage.url().includes("/login")) {
    await garage
      .getByRole("combobox", { name: "Free model library" })
      .waitFor({ timeout: 20000 });
    if (
      (await garage
        .locator("section[data-model-id]")
        .getAttribute("data-model-id")) !== "bmw-m3-e30"
    )
      throw new Error("Garageexactmatchfailed");
    await garage
      .getByRole("combobox", { name: "Free model library" })
      .selectOption("audi-r8");
    await garage.reload({ waitUntil: "networkidle" });
    if (
      (await garage
        .locator("section[data-model-id]")
        .getAttribute("data-model-id")) !== "audi-r8"
    )
      throw new Error("Garagesavefailed");
    await garage.screenshot({
      path: `${output}/garage-desktop.png`,
      fullPage: true,
    });
    await garage.setViewportSize({ width: 390, height: 844 });
    if (
      await garage.evaluate(
        () => document.documentElement.scrollWidth > innerWidth,
      )
    )
      throw new Error("GarageMobileoverflow");
    await garage.screenshot({
      path: `${output}/garage-mobile.png`,
      fullPage: true,
    });
    garageResult = "exact-match-and-save-pass";
  }
  await writeFile(
    `${output}/flows-report.json`,
    JSON.stringify(
      {
        previews: 25,
        noAutomaticDownloads: true,
        paint: "pass",
        export: dimensions,
        mobile: "pass",
        saveRestore: "pass",
        garage: garageResult,
        errors,
        badResponses,
      },
      null,
      2,
    ),
  );
  if (errors.length || badResponses.length)
    throw new Error([...errors, ...badResponses].join("\n"));
  console.log(
    `PASS:25previews,paint,PNGexport,mobile,persistence;garage=${garageResult}`,
  );
} catch (error) {
  process.exitCode = 1;
  console.error(error);
} finally {
  const shutdown = setTimeout(() => process.exit(process.exitCode ?? 0), 5000);
  shutdown.unref();
  await context.close();
  await browser.close();
  clearTimeout(shutdown);
}
